package com.suiting.podcast

import org.junit.Assert.*
import org.junit.Test

class PodcastTest {
    @Test fun paragraphsAndLengthRemainNavigable() {
        val input = "你好，这是第一段。\r\n\r\n" + "春天的风。".repeat(120)
        val chunks = TextSegments.split(input, limit = 220)
        assertEquals("你好，这是第一段。", chunks.first().text)
        assertTrue(chunks.all { it.text.length <= 220 && it.text.isNotBlank() })
        assertEquals(input.replace("\r\n", ""), chunks.joinToString("") { it.text })
    }
    @Test fun emojiIsNeverSplitBetweenSurrogates() {
        val input = "甲".repeat(219) + "😀" + "乙".repeat(500)
        val chunks = TextSegments.split(input, limit = 220)
        assertEquals(input, chunks.joinToString("") { it.text })
        assertTrue(chunks.all { !Character.isHighSurrogate(it.text.last()) && !Character.isLowSurrogate(it.text.first()) })
    }
    @Test(expected = IllegalArgumentException::class) fun inputLimitProtectsStorage() { TextSegments.split("字".repeat(TextSegments.MAX_INPUT + 1)) }
    @Test(expected = IllegalArgumentException::class) fun blankTextIsRejected() { TextSegments.split("\n \u0000") }
    @Test fun progressAndSegmentsSurviveSerialization() {
        val episode = Episode(title = "正文与\"引号\"", voice = "system", segments = listOf(Segment("你好", 2500), Segment("再见", 3000)), status = "paused", error = "网络中断", segmentIndex = 1, positionMs = 1234)
        assertEquals(listOf(episode), EpisodeCodec.decode(EpisodeCodec.encode(listOf(episode))))
    }
    @Test(expected = IllegalArgumentException::class) fun manifestCannotEscapeAudioDirectory() {
        val raw = EpisodeCodec.encode(listOf(Episode(id = "../outside", title = "x", voice = "system", segments = listOf(Segment("x")))))
        EpisodeCodec.decode(raw)
    }
    @Test fun persistedIndexAndPositionAreClamped() {
        val episode = Episode(title = "test", voice = "system", segments = listOf(Segment("一")), segmentIndex = 99, positionMs = -1)
        val loaded = EpisodeCodec.decode(EpisodeCodec.encode(listOf(episode))).single()
        assertEquals(0, loaded.segmentIndex); assertEquals(0L, loaded.positionMs)
    }
    @Test fun tokenMatchesUpstreamReferenceAtDifferentDates() {
        // Golden vectors generated by tools/reference_edge_drm.py with explicit timestamps.
        assertEquals("52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6", EdgeToken.generate(0))
        assertEquals("2CD23A2CA0B2595A-F3C846C370E05F9CC83ACC5F995C5F5D87A4D0F14CE8936A0F902E64099E38A2", EdgeToken.generate(1700000000))
        assertEquals("7A2F735C072A520E-E7898B992D84E02F77B6307BA867E23A4AE425A89A4959EA864E8885D540A3F8", EdgeToken.generate(1792857600))
    }
    @Test fun tokenBucketsChangeOnlyEveryFiveMinutes() {
        assertEquals(EdgeToken.generate(1792857600), EdgeToken.generate(1792857899))
        assertNotEquals(EdgeToken.generate(1792857600), EdgeToken.generate(1792857900))
    }
    @Test fun binaryAudioFramingExcludesHeaders() {
        val header = "Content-Type:audio/mpeg\r\nPath:audio\r\n".toByteArray()
        val audio = byteArrayOf(0xff.toByte(), 0xfb.toByte(), 2, 3)
        val packet = byteArrayOf((header.size shr 8).toByte(), header.size.toByte()) + header + audio
        assertArrayEquals(audio, EdgeSpeechEngine.audioPayload(packet))
        assertEquals("&lt;x a=&quot;y&quot;&gt;&amp;&apos;", EdgeSpeechEngine.escape("<x a=\"y\">&'"))
    }
    @Test(expected = IllegalArgumentException::class) fun truncatedAudioFrameIsRejected() { EdgeSpeechEngine.audioPayload(byteArrayOf(0, 100, 1)) }
}
